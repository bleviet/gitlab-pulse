const VALID_IDS = new Set<string>(UI_THEMES.map((t) => t.id));

export function parseUiTheme(raw: string | null | undefined): UiThemeId {
  if (raw && VALID_IDS.has(raw)) return raw as UiThemeId;
  return "bahonavi";
}

export function getUiTheme(id: UiThemeId): UiThemeDefinition {
  return UI_THEMES.find((t) => t.id === id) ?? UI_THEMES[0];
}

export function resolveUserPalette(
  serverPalette: Record<string, string>,
  themeId: UiThemeId,
  mode: ThemeMode,
): Record<string, string> {
  const def = getUiTheme(themeId);
  if (!def.dataPalette) return serverPalette;
  return { ...serverPalette, ...def.dataPalette[mode] };
}
